#!/usr/bin/env python3
"""Generate browser language resources from the shared English/Swedish catalogue."""
from pathlib import Path
import json
root = Path(__file__).resolve().parent.parent
catalogue = json.loads((root/'assets/locales/sv.json').read_text(encoding='utf-8'))
helper = r'''// Generated by scripts/generate-locales.py. No remote translation service.
var StrataLocale = (() => {
  const api = typeof browser !== "undefined" ? browser : chrome;
  const catalogue = CATALOGUE;
  let language = /^sv(?:[-_]|$)/i.test(api.i18n?.getUILanguage?.() || "en") ? "sv" : "en";
  function setLanguage(value) { if (value === "sv" || value === "en") language = value; }
  function t(key, values = {}) {
    const result = language === "sv" ? catalogue[key] || key : key;
    return result.replace(/\{(\w+)\}/g, (match, name) => values[name] === undefined ? match : String(values[name]));
  }
  function error(value) {
    if (language !== "sv") return String(value);
    let result = String(value);
    for (const key of Object.keys(catalogue).filter(key => key.length >= 12 && !key.includes("{")).sort((a,b) => b.length-a.length)) result = result.split(key).join(catalogue[key]);
    return result;
  }
  function apply(root = document) {
    if (!root.querySelectorAll) return;
    root.documentElement.lang = language;
    for (const element of root.querySelectorAll("h1,p,small,strong,label,button,summary,.diagnostics")) {
      if (element.children.length || ["status", "last-issue"].includes(element.id)) continue;
      element.dataset.english ??= element.textContent;
      element.textContent = t(element.dataset.english);
    }
    for (const element of root.querySelectorAll("[placeholder]")) {
      element.dataset.englishPlaceholder ??= element.placeholder;
      element.placeholder = t(element.dataset.englishPlaceholder);
    }
  }
  return {t, error, apply, setLanguage};
})();
'''.replace('CATALOGUE', json.dumps(catalogue, ensure_ascii=False, separators=(',',':')))
description='Capture browser downloads in StrataFetch. Start the download in the app or cancel.'
for browser in ['chromium','firefox']:
    folder=root/'extensions'/browser
    (folder/'locale.js').write_text(helper,encoding='utf-8')
    for language, text in [('en',description),('sv','Fånga webbläsarhämtningar med StrataFetch. Starta hämtningen i appen eller avbryt.')]:
        destination=folder/'_locales'/language
        destination.mkdir(parents=True,exist_ok=True)
        (destination/'messages.json').write_text(json.dumps({'extensionDescription':{'message':text}},ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print('Generated shared browser language resources.')
